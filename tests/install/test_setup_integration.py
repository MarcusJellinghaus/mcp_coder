"""Real-toolchain integration tests for ``mcp-coder setup``.

Each test writes a throwaway npm, Rust or Python project into ``tmp_path``
and runs ``sys.executable -m mcp_coder setup`` against it, so the code under
test is this checkout, never the ``mcp-coder`` on ``PATH``. A test whose
toolchain (``npm``, ``cargo``, ``uv``) is missing skips. The fixtures declare
no dependencies, so nothing beyond the toolchains' own build tooling needs
the network.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

import git
import pytest

from mcp_coder.install import _env

pytestmark = pytest.mark.setup_integration

_NPM_NAME = "setup-npm-fixture"
_RUST_NAME = "setup-rust-fixture"


def _require(tool: str) -> None:
    """Skip the test unless ``tool`` is on PATH."""
    if shutil.which(tool) is None:
        pytest.skip(f"{tool} not on PATH")


def _run_setup(project: Path, *extra: str) -> subprocess.CompletedProcess[str]:
    """Run ``mcp-coder setup`` for ``project`` from this checkout."""
    return subprocess.run(
        [
            sys.executable,
            "-m",
            "mcp_coder",
            "setup",
            "--project-dir",
            str(project),
            *extra,
        ],
        capture_output=True,
        text=True,
        check=False,
    )


def _output(result: subprocess.CompletedProcess[str]) -> str:
    """Return stdout and stderr of ``result``, for assertions and messages."""
    return f"{result.stdout}\n{result.stderr}"


def _git_commit_all(path: Path, gitignore: str) -> None:
    """``git init`` ``path``, write ``.gitignore`` and commit everything."""
    (path / ".gitignore").write_text(gitignore, encoding="utf-8")
    repo = git.Repo.init(path)
    with repo.config_writer() as config:
        config.set_value("user", "name", "Test User")
        config.set_value("user", "email", "test@example.com")
    repo.git.add("-A")
    repo.git.commit("-m", "fixture")
    repo.close()


def _npm_fixture(path: Path) -> None:
    """Write a dependency-free npm project whose setup runs ``npm ci``."""
    package = {"name": _NPM_NAME, "version": "0.1.0", "private": True}
    lock = {
        "name": _NPM_NAME,
        "version": "0.1.0",
        "lockfileVersion": 3,
        "requires": True,
        "packages": {"": {"name": _NPM_NAME, "version": "0.1.0"}},
    }
    (path / "package.json").write_text(json.dumps(package, indent=2), "utf-8")
    (path / "package-lock.json").write_text(json.dumps(lock, indent=2), "utf-8")
    (path / "mcp-coder.toml").write_text(
        '[tool.mcp-coder.setup]\nsteps = [{ argv = ["npm", "ci"] }]\n',
        encoding="utf-8",
    )


def _rust_fixture(path: Path) -> None:
    """Write a dependency-free Rust crate whose setup runs ``cargo fetch``."""
    (path / "Cargo.toml").write_text(
        "[package]\n"
        f'name = "{_RUST_NAME}"\n'
        'version = "0.1.0"\n'
        'edition = "2021"\n'
        "\n"
        "[dependencies]\n",
        encoding="utf-8",
    )
    (path / "src").mkdir()
    (path / "src" / "main.rs").write_text("fn main() {}\n", encoding="utf-8")
    (path / "Cargo.lock").write_text(
        "# This file is automatically @generated by Cargo.\n"
        "# It is not intended for manual editing.\n"
        "version = 3\n"
        "\n"
        "[[package]]\n"
        f'name = "{_RUST_NAME}"\n'
        'version = "0.1.0"\n',
        encoding="utf-8",
    )
    (path / "mcp-coder.toml").write_text(
        '[tool.mcp-coder.setup]\nsteps = [{ argv = ["cargo", "fetch", "--locked"] }]\n',
        encoding="utf-8",
    )


def _python_fixture(path: Path) -> None:
    """Write a trivial, dependency-free local package (default setup)."""
    (path / "pyproject.toml").write_text(
        "[build-system]\n"
        'requires = ["setuptools>=61.0"]\n'
        'build-backend = "setuptools.build_meta"\n'
        "\n"
        "[project]\n"
        'name = "setup-integration-fixture"\n'
        'version = "0.1.0"\n'
        'requires-python = ">=3.11"\n'
        "\n"
        "[tool.setuptools]\n"
        'py-modules = ["setup_integration_fixture"]\n'
        "\n"
        "[tool.mcp-coder.install]\n"
        'extras = ""\n',
        encoding="utf-8",
    )
    (path / "setup_integration_fixture.py").write_text("VALUE = 42\n", encoding="utf-8")


def test_npm_setup(tmp_path: Path) -> None:
    _require("npm")
    _npm_fixture(tmp_path)
    _git_commit_all(tmp_path, "node_modules/\n")

    result = _run_setup(tmp_path)

    assert result.returncode == 0, _output(result)


def test_rust_setup(tmp_path: Path) -> None:
    _require("cargo")
    _rust_fixture(tmp_path)

    result = _run_setup(tmp_path)

    assert result.returncode == 0, _output(result)


def test_python_setup(tmp_path: Path) -> None:
    _require("uv")
    _python_fixture(tmp_path)

    result = _run_setup(tmp_path, "--skip-overrides")

    assert result.returncode == 0, _output(result)
    assert (_env.venv_bin(tmp_path / ".venv") / _env.exe("python")).exists()


def test_python_setup_untracked_lockfile_fails(tmp_path: Path) -> None:
    _require("uv")
    _python_fixture(tmp_path)
    _git_commit_all(tmp_path, ".venv/\n")

    result = _run_setup(tmp_path, "--skip-overrides")

    # uv sync creates uv.lock: neither tracked nor ignored.
    assert result.returncode != 0, _output(result)
    assert "uv.lock" in _output(result)
